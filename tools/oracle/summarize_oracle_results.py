#!/usr/bin/env python3
"""
summarize_oracle_results.py — Produce sanitized oracle summary for Gate 6 evidence.

Reads the local comparison results from .local/oracle/fods/ and produces:
  - A sanitized YAML summary (local: .local/oracle/fods/oracle-summary-sanitized.yaml)
  - A committed markdown report (acquisition-packs/fods/gate6-oracle-comparison-report.md)

Only sanitized aggregates are written to committed paths. Raw data stays local.

Usage:
    python tools/oracle/summarize_oracle_results.py [--dry-run]

Rules:
    - No network calls
    - No LLM calls
    - No product source
    - Raw oracle data stays in .local/oracle/fods/ (never committed)
    - Only sanitized summary committed to acquisition-packs/
    - Gate 6 approval is human-only
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from oracle_common import (
    COMPARISON_REPORT_PATH,
    ORACLE_LOCAL_DIR,
    SANITIZED_YAML_PATH,
    SUMMARY_PATH,
)


def load_summary() -> dict:
    if not SUMMARY_PATH.exists():
        return None
    return json.loads(SUMMARY_PATH.read_text(encoding="utf-8"))


def write_sanitized_yaml(summary: dict):
    ORACLE_LOCAL_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Sanitized oracle summary — local-only",
        f"total_samples: {summary['total']}",
        f"pass: {summary['pass']}",
        f"warn: {summary['warn']}",
        f"fail: {summary['fail']}",
        f"incomplete: {summary['incomplete']}",
        f"oracle_missing: {summary['oracle_missing']}",
        "samples:",
    ]
    for s in summary["samples"]:
        lines.append(f"  - sample: {s['sample']}")
        lines.append(f"    status: {s['status']}")
        lines.append(f"    oracle_sheet_count: {s['oracle_sheet_count']}")
        lines.append(f"    parser_sheet_count: {s['parser_sheet_count']}")
        lines.append(f"    cell_count_delta: {s['cell_count_delta']}")
        lines.append(f"    formula_representation_differences: {s['formula_representation_differences']}")
        lines.append(f"    discrepancy_count: {s['discrepancy_count']}")
    SANITIZED_YAML_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_committed_report(summary: dict, dry_run: bool = False):
    overall = "oracle_comparison_created_pending_independent_verification"
    if summary["fail"] > 0:
        overall = "oracle_comparison_needs_revision"
    elif summary["oracle_missing"] > 0:
        overall = "oracle_blocked_missing_tool"

    lines = [
        "---",
        "artifact_id: fods-gate6-oracle-comparison-report",
        "artifact_type: gate-comparison-report",
        f"path: {COMPARISON_REPORT_PATH}",
        "format_id: fods",
        "visibility: internal",
        "publish_allowed: false",
        "generated_by: claude",
        "generated_at: \"2026-05-07\"",
        "notes: \"Gate 6 oracle comparison report for FODS. Auto-generated by summarize_oracle_results.py.\"",
        "---",
        "",
        "# FODS Gate 6 Oracle Comparison Report",
        "",
        "**Format:** FODS",
        "**Gate:** 6 — Oracle Comparison",
        f"**Status:** {overall}",
        "**Gate 6 approved:** NO — requires independent verification (TC-0027) then human approval",
        "",
        "---",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Total samples | {summary['total']} |",
        f"| PASS | {summary['pass']} |",
        f"| WARN | {summary['warn']} |",
        f"| FAIL | {summary['fail']} |",
        f"| Oracle missing | {summary['oracle_missing']} |",
        "",
        "---",
        "",
        "## Per-Sample Results",
        "",
        "| Sample | Status | Oracle Sheets | Parser Sheets | Cell Delta | Formula Diffs |",
        "|---|---|---|---|---|---|",
    ]
    for s in summary["samples"]:
        lines.append(
            f"| {s['sample']} | {s['status']} | "
            f"{s['oracle_sheet_count']} | {s['parser_sheet_count']} | "
            f"{s['cell_count_delta']} | {s['formula_representation_differences']} |"
        )

    lines += [
        "",
        "---",
        "",
        "## Formula Representation Note",
        "",
        "Parser stores raw formula text (e.g. `oooc:=SUM([.B1:.B3])`). Oracle CSV exports may contain",
        "the evaluated numeric result. This is a KNOWN_FORMULA_REPRESENTATION_DIFFERENCE and does",
        "not constitute a Gate 6 failure per the scope defined in `acquisition-packs/fods/oracle-scope.md`.",
        "",
        "---",
        "",
        "## Evidence References",
        "",
        "| Evidence | Location |",
        "|---|---|",
        "| Local comparison summary | `.local/oracle/fods/comparison-summary.json` (not committed) |",
        "| Per-sample results | `.local/oracle/fods/per-sample-results/*.json` (not committed) |",
        "| Oracle manifest | `.local/oracle/fods/oracle-manifest.yaml` (not committed) |",
        "| Sanitized summary | `.local/oracle/fods/oracle-summary-sanitized.yaml` (not committed) |",
        "| Gate 5 neutral model | `schemas/neutral-model/fods/` |",
        "| Prototype parser | `prototypes/by-format/fods/fods_parser.py` |",
        "| Oracle tooling | `tools/oracle/` |",
        "",
        "---",
        "",
        "## Gate 6 Approval Gate",
        "",
        "Gate 6 is NOT approved. This report is produced for human review after TC-0027",
        "independent verification completes. Only a human can approve Gate 6.",
    ]

    content = "\n".join(lines) + "\n"
    if dry_run:
        print(content[:500])
        print("[dry-run — not written]")
    else:
        COMPARISON_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        COMPARISON_REPORT_PATH.write_text(content, encoding="utf-8")
        print(f"Report written to: {COMPARISON_REPORT_PATH}")

    return overall


def main():
    import argparse
    parser = argparse.ArgumentParser(description="Summarize FODS oracle results")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    print("=" * 60)
    print("FODS Oracle Results Summarizer")
    print("=" * 60)

    summary = load_summary()
    if not summary:
        print(f"ERROR: Comparison summary not found at {SUMMARY_PATH}")
        print("Run: python tools/oracle/compare_fods_oracle.py first")
        print("ORACLE_SUMMARIZE: FAIL")
        return 1

    write_sanitized_yaml(summary)
    print(f"Sanitized YAML written to: {SANITIZED_YAML_PATH}")

    overall = write_committed_report(summary, dry_run=args.dry_run)

    print()
    print(f"Overall Gate 6 status: {overall}")
    print("ORACLE_SUMMARIZE: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
