# Stable anchor names — exported for test assertions
REQUIRED_ANCHORS = [
    "status-at-a-glance",
    "machinery-lane",
    "product-lane",
    "shared-boundaries",
    "known-limitations",
    "generation-evidence",
]

# Layer paths that are gitignored local state — suppress file counts for these
GITIGNORED_LAYER_PATHS = {".local/supervisor/", ".local/evidences/"}


def _anchor(name: str) -> str:
    """Return a stable HTML anchor tag."""
    return f'<a name="{name}"></a>'


def _read_yaml(path: Path):
    if not path.exists():
        return None
    try:
        import yaml
        return yaml.safe_load(path.read_text(encoding="utf-8", errors="replace"))
    except Exception:
        return None


def _read_json(path: Path):
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8", errors="replace"))
    except Exception:
        return None


def _get_head_revision(repo_root: Path) -> str:
    """Return short git HEAD SHA, or 'UNKNOWN' if not available."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, cwd=str(repo_root), timeout=10,
        )
        if result.returncode == 0:
            return result.stdout.strip()
    except Exception:
        pass
    return "UNKNOWN"


def _atomic_write(target: Path, content: str) -> None:
    """Write content to target atomically via a .tmp file."""
    tmp = target.with_suffix(".tmp")
    try:
        tmp.write_text(content, encoding="utf-8")
        tmp.replace(target)
    except Exception:
        if tmp.exists():
            try:
                tmp.unlink()
            except Exception:
                pass
        raise


def validate_output(content: str) -> list[str]:
    """Validate generated content against the two-lane contract.

    Returns a list of violation strings; empty list means PASS.
    """
    violations = []

    if "DO NOT EDIT MANUALLY" not in content:
        violations.append("Missing 'DO NOT EDIT MANUALLY' marker")

    required_sections = [
        "## Machinery Lane",
        "## Product Lane",
        "## Shared Boundaries",
        "## Generation and Evidence",
    ]
    for section in required_sections:
        if section not in content:
            violations.append(f"Missing required section: {section!r}")

    for anchor in REQUIRED_ANCHORS:
        count = content.count(f'name="{anchor}"')
        if count == 0:
            violations.append(f"Missing required anchor: {anchor!r}")
        elif count > 1:
            violations.append(f"Duplicate anchor: {anchor!r} appears {count} times")

    return violations


