def generate_project_status(
    repo_root: Path = REPO_ROOT,
    output_path: Path | None = None,
    dry_run: bool = False,
    timestamp_override: str | None = None,
) -> str:
    """Generate the full two-lane PROJECT_STATUS.md content."""
    timestamp = timestamp_override or datetime.now(timezone.utc).isoformat(timespec="seconds")
    head_revision = _get_head_revision(repo_root)

    # Collect all data
    stats = collect_statistics(repo_root)
    inventory = collect_product_inventory(repo_root)
    arch = collect_architecture_inventory(repo_root)
    agents = collect_agent_inventory(repo_root)

    # Assemble two-lane document
    parts = [
        _generate_header(timestamp),
        _render_status_at_a_glance(stats, agents),
        _render_machinery_lane(stats, arch, agents),
        _render_product_lane(stats, inventory, arch),
        _render_shared_boundaries(stats),
        _generate_limitations(repo_root, stats, inventory),
        _render_generation_evidence(timestamp, head_revision, repo_root),
    ]
    content = "\n".join(parts)

    if not dry_run:
        target = output_path or (repo_root / "PROJECT_STATUS.md")
        _atomic_write(target, content)
        print(f"Written to {target}", file=sys.stderr)

    return content


def update_readme(repo_root: Path, stats: dict) -> None:
    """Inject PROJECT_STATUS.md reference into README.md using markers."""
    readme_path = repo_root / "README.md"
    if not readme_path.exists():
        return

    readme = readme_path.read_text(encoding="utf-8")
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    oracle = stats.get("oracle", {})
    gov = stats.get("governance", {})
    infra = stats.get("infrastructure", {})
    fmt = stats.get("formats", {})
    cert = stats.get("certification", {})

    block = "\n".join([
        f"<!-- BEGIN:PROJECT-STATUS-REF generated={timestamp} source=PROJECT_STATUS.md -->",
        f"**Quick numbers (machinery):** {gov.get('validators', 0)} validators | "
        f"{gov.get('skills', 0)} skills | "
        f"{infra.get('sprint_count', 0)} sprints",
        "",
        f"**Quick numbers (product):** {fmt.get('active_with_source', 0)} active formats | "
        f"{oracle.get('pass_rate', 'N/A')} oracle cases | "
        f"{cert.get('certified', 0)}/{cert.get('total', 0)} certified",
        "",
        "For full auto-generated project status with per-format details and two-lane "
        "(machinery / product) breakdown, see "
        "[PROJECT_STATUS.md](PROJECT_STATUS.md#status-at-a-glance).",
        "<!-- END:PROJECT-STATUS-REF -->",
    ])

    begin_marker = "<!-- BEGIN:PROJECT-STATUS-REF"
    end_marker = "<!-- END:PROJECT-STATUS-REF -->"

    if begin_marker in readme:
        pattern = re.compile(
            r"<!-- BEGIN:PROJECT-STATUS-REF[^\n]*-->.*?<!-- END:PROJECT-STATUS-REF -->",
            re.DOTALL,
        )
        readme = pattern.sub(block, readme)
    else:
        insert_point = readme.find("## Keeping This README Current")
        if insert_point >= 0:
            readme = readme[:insert_point] + block + "\n\n" + readme[insert_point:]
        else:
            readme = readme.rstrip() + "\n\n" + block + "\n"

    readme_path.write_text(readme, encoding="utf-8")
    print("Updated README.md with PROJECT_STATUS.md reference", file=sys.stderr)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate PROJECT_STATUS.md")
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument("--dry-run", action="store_true",
                        help="Return content without writing file")
    parser.add_argument("--validate", action="store_true",
                        help="Validate structure and exit 0/1")
    parser.add_argument("--timestamp", type=str, default=None,
                        help="Override timestamp for deterministic output")
    parser.add_argument("--json", action="store_true",
                        help="Output raw collected data as JSON")
    parser.add_argument("--update-readme", action="store_true",
                        help="Also inject reference into README.md")
    args = parser.parse_args()

    if args.json:
        data = {
            "statistics": collect_statistics(args.repo_root),
            "product_inventory": collect_product_inventory(args.repo_root),
            "architecture": collect_architecture_inventory(args.repo_root),
            "agents": collect_agent_inventory(args.repo_root),
        }
        print(json.dumps(data, indent=2, default=str))
        return 0

    if args.validate:
        content = generate_project_status(
            args.repo_root,
            dry_run=True,
            timestamp_override=args.timestamp,
        )
        violations = validate_output(content)
        if violations:
            print("VIOLATIONS:", file=sys.stderr)
            for v in violations:
                print(f"  - {v}", file=sys.stderr)
            return 1
        print("VALID: PROJECT_STATUS.md contract satisfied")
        return 0

    content = generate_project_status(
        args.repo_root,
        args.output,
        args.dry_run,
        timestamp_override=args.timestamp,
    )

    if args.dry_run:
        print(content)

    if args.update_readme:
        stats = collect_statistics(args.repo_root)
        update_readme(args.repo_root, stats)

    return 0


if __name__ == "__main__":
    sys.exit(main())
