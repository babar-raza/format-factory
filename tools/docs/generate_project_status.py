def _generate_limitations(repo_root: Path, stats: dict, inventory: dict | None = None) -> str:
    lines = [
        _anchor("known-limitations"),
        "## Known Limitations",
        "",
    ]

    # Machinery Limitations
    lines += [
        "### Machinery Limitations",
        "",
        "- **LAYER_DEFINITIONS is hardcoded** in `generate_architecture_inventory.py` — "
        "not derived from a registry. Manual update required when adding layers.",
        "- **L08/L09** are gitignored local state; file counts vary by machine.",
        "- **Checkpoint interval** is not configured in `.supervisor/policies.yaml`.",
        "",
    ]

    # Product Limitations
    lines += [
        "### Product Limitations",
        "",
    ]

    # Formats without source — derive from inventory or registry
    no_source = []
    if inventory:
        inv_list = inventory if isinstance(inventory, list) else inventory.get("formats", [])
        no_source = [
            f.get("format_id", "?").upper()
            for f in inv_list
            if not f.get("has_source", False)
        ]
    else:
        try:
            import yaml
            reg = yaml.safe_load(
                (repo_root / "registry" / "format-registry.yaml").read_text(
                    encoding="utf-8", errors="replace"
                )
            )
            for f in reg.get("formats", []):
                fid = f.get("format_id", "")
                if fid == "odf-shared":
                    continue
                if not (repo_root / "src" / "python" / fid).is_dir():
                    no_source.append(fid.upper())
        except Exception:
            pass

    if no_source:
        lines.append(
            f"- **Formats without source** ({len(no_source)}): "
            f"{', '.join(no_source)} (no product_track)"
        )
    lines += [
        "- **PyPI publication**: All Python packages are local-only; not published to PyPI",
        "",
    ]

    # Release Limitations
    lines += [
        "### Release Limitations",
        "",
        "- **Commercial .NET release**: Gate 11 execution approval pending (Babar Raza)",
        "- **External users**: No external users yet; all testing is internal",
        "",
    ]

    return "\n".join(lines)


