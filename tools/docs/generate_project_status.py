def _render_machinery_lane(stats: dict, arch: dict, agents: dict) -> str:
    gov = stats.get("governance", {})
    layers = arch.get("layers", [])
    validators_data = arch.get("validators", {})
    capabilities_data = arch.get("capabilities", {})
    skills_data = arch.get("skills", {})
    gates = arch.get("gates", [])

    policies = agents.get("policies", {})
    prohibitions = policies.get("hard_prohibitions", [])
    infra = stats.get("infrastructure", {})

    lines = [
        _anchor("machinery-lane"),
        "## Machinery Lane",
        "",
        "Governance, supervision, validators, capabilities, and skills. "
        "These metrics describe the health of the autonomous machinery itself.",
        "",
    ]

    # Architecture and Layer Inventory
    lines += [
        _anchor("machinery-architecture"),
        "### Architecture and Layer Inventory",
        "",
        "Format Factory uses 11 independent layers, each with defined responsibilities.",
        "",
        "| Layer | Name | Purpose | Files |",
        "|---|---|---|---|",
    ]
    for layer in layers:
        paths = layer.get("paths", [])
        is_gitignored = any(
            any(gs in p for gs in GITIGNORED_LAYER_PATHS)
            for p in paths
        )
        if is_gitignored:
            file_count = "(gitignored local state)"
        else:
            file_count = str(layer.get("file_count", 0))
        lines.append(
            f"| {layer['id']} | {layer['name']} | {layer['purpose']} | {file_count} |"
        )
    lines.append("")

    # Governance Validators
    lines += [
        _anchor("machinery-validators"),
        "### Governance Validators",
        "",
        f"**{validators_data.get('total', 0)} validators** across "
        f"**{validators_data.get('module_count', 0)} modules** "
        f"(source: `tools/supervisor/governance_validators*.py`)",
        "",
        "| Module | Validators |",
        "|---|---|",
    ]
    for mod_name, names in validators_data.get("modules", {}).items():
        lines.append(f"| `{mod_name}` | {len(names)} |")
    lines.append("")

    # Capabilities and Skills
    cap_active = capabilities_data.get("active", 0)
    cap_total = capabilities_data.get("total", 0)
    tracks = capabilities_data.get("tracks", {})

    lines += [
        _anchor("machinery-capabilities"),
        "### Capabilities and Skills",
        "",
        f"**{cap_active} active** of {cap_total} total capabilities "
        f"(source: `.governance/capabilities/registry.yaml`)",
        "",
        "| Product Track | Count |",
        "|---|---|",
    ]
    for track, count in sorted(tracks.items()):
        display_track = "(no product_track)" if track == "unclassified" else track
        lines.append(f"| {display_track} | {count} |")
    if any(t == "unclassified" for t in tracks):
        lines.append("")
        lines.append(
            "_Note: (no product_track) = no product_track assigned — machinery/infra tier_"
        )
    lines.append("")

    skill_total = skills_data.get("total", 0)
    skill_statuses = skills_data.get("statuses", {})
    lines += [
        f"**{skill_total} skills** registered (source: `.supervisor/skill-registry.yaml`)",
        "",
    ]
    if skill_statuses:
        lines += ["| Status | Count |", "|---|---|"]
        for st, count in sorted(skill_statuses.items()):
            lines.append(f"| {st} | {count} |")
        lines.append("")

    # Supervisor and Autonomous Execution
    max_iter = policies.get("max_iterations", "N/A")
    ckpt = policies.get("checkpoint_interval")
    ckpt_display = "not configured" if ckpt is None else str(ckpt)
    sprint_count = infra.get("sprint_count", 0)
    avg_quality = infra.get("avg_quality", 0.0)

    lines += [
        _anchor("machinery-supervision"),
        "### Supervisor and Autonomous Execution",
        "",
        f"- **Autonomous sprints completed:** {sprint_count} "
        f"(source: `reports/supervisor/maturity-trend.json`)",
        f"- **Avg evidence quality:** {avg_quality:.2f} (0.0–1.0 scale)",
        f"- **Max iterations per session:** {max_iter} "
        f"(source: `.supervisor/policies.yaml`)",
        f"- **Checkpoint interval:** {ckpt_display}",
        "",
    ]

    if prohibitions:
        lines += [
            "**Hard prohibitions** (from `.supervisor/policies.yaml`):",
            "",
        ]
        for p in prohibitions:
            note = ""
            # Cross-check: gate_N_approval prohibition with autonomous gates
            gate_match = re.match(r"gate_(\d+)_approval", p)
            if gate_match:
                gate_num = gate_match.group(1)
                matching_gates = [
                    g for g in gates
                    if str(g.get("gate_id", "")).endswith(gate_num)
                    and g.get("autonomous", True)
                ]
                if matching_gates:
                    note = (
                        " _(business security sign-off, distinct from "
                        f"executing Gate {gate_num} technical steps)_"
                    )
            lines.append(f"- `{p}`{note}")
        lines.append("")

    # Machinery Limitations
    lines += [
        _anchor("machinery-limitations"),
        "### Machinery Limitations",
        "",
        "- **LAYER_DEFINITIONS is hardcoded** in `generate_architecture_inventory.py` — "
        "layer paths are not derived from a registry. Adding a new layer requires "
        "updating the constant manually.",
        "- **L08/L09 file counts** are gitignored local state — counts vary by machine "
        "and session; not meaningful for cross-machine comparison.",
        "- **Governance validator runner** is not integrated into pre-commit hooks for "
        "all validators — only a subset are enforced at commit time.",
        "",
    ]

    return "\n".join(lines)


def _render_product_lane(stats: dict, inventory: list, arch: dict) -> str:
    oracle = stats.get("oracle", {})
    fmt = stats.get("formats", {})
    cert = stats.get("certification", {})
    gates = arch.get("gates", [])

    formats_list = inventory if isinstance(inventory, list) else []
    total_in_registry = fmt.get("total_in_registry", 0)
    active_with_source = fmt.get("active_with_source", 0)
    families = fmt.get("families", {})

    lines = [
        _anchor("product-lane"),
        "## Product Lane",
        "",
        "Format implementations, oracle verification, certification, and gates. "
        "These metrics describe the health and completeness of the product itself.",
        "",
    ]

    # Format and Family Inventory
    lines += [
        _anchor("product-inventory"),
        "### Format and Family Inventory",
        "",
        f"**{total_in_registry} formats** in registry (excluding odf-shared shared library). "
        f"**{active_with_source} formats** have Python source. "
        f"**{len(families)} families**: {', '.join(sorted(families.keys()))}.",
        "",
        "Source: `registry/format-registry.yaml`",
        "",
    ]

    # Per-format table
    if formats_list:
        lines += [
            "| Format | Family | Source | Oracle | Certified | Gate |",
            "|---|---|---|---|---|---|",
        ]
        for f in formats_list:
            fid = f.get("format_id", "?")
            family = f.get("family", "?")
            has_src = f.get("has_source", False)
            src_mark = "yes" if has_src else "-"
            oracle_rate = f.get("oracle_pass_rate", "N/A")
            if not has_src and oracle_rate in ("N/A", None):
                oracle_rate = "- (no source)"
            cert_status = f.get("certification_status", "N/A")
            if not has_src and cert_status in ("N/A", None):
                cert_status = "- (no source)"
            gate_summary = f.get("gate_summary", "N/A")
            lines.append(
                f"| {fid} | {family} | {src_mark} | {oracle_rate} | {cert_status} | {gate_summary} |"
            )
        lines.append("")

    # Oracle Verification
    formats_verified = oracle.get("formats_verified", 0)
    total_cases = oracle.get("total_cases", 0)
    total_pass = oracle.get("total_pass", 0)
    pass_rate = oracle.get("pass_rate", "0/0")

    lines += [
        _anchor("product-oracle"),
        "### Oracle Verification",
        "",
        f"**{formats_verified} of {total_in_registry - 1} tracked formats** have oracle results. "
        f"Pass rate: **{pass_rate}** ({total_pass}/{total_cases} cases).",
        "",
        "Source: `oracle/formats/*/reports/oracle-run-summary.json`",
        "",
    ]

    # Certification Status
    certified = cert.get("certified", 0)
    cert_total = cert.get("total", 0)

    lines += [
        _anchor("product-certification"),
        "### Certification Status",
        "",
        f"**{certified} of {cert_total} formats with source** are certified. "
        "Formats without source are excluded from this count.",
        "",
        "Source: `reports/certification/portfolio-certification-matrix.json`",
        "",
    ]

    # Gate Progress
    lines += [
        _anchor("product-gates"),
        "### Gate Progress",
        "",
        f"**{len(gates)} gates** in the acquisition pipeline "
        f"(source: `registry/gate-contract-registry.yaml`).",
        "",
    ]
    if gates:
        lines += [
            "| Gate | Title | Agent-Executable |",
            "|---|---|---|",
        ]
        for g in gates:
            auto = "Yes" if g.get("autonomous", True) else "No (human required)"
            lines.append(f"| {g['gate_id']} | {g['title']} | {auto} |")
        lines.append("")

    # Product Maturity
    lines += [
        _anchor("product-maturity"),
        "### Product Maturity",
        "",
        "Maturity dimensions per format: REGISTERED → SOURCE_PRESENT → ORACLE_VERIFIED → CERTIFIED",
        "",
        f"- **REGISTERED**: {total_in_registry} formats",
        f"- **SOURCE_PRESENT**: {active_with_source} formats",
        f"- **ORACLE_VERIFIED**: {formats_verified} formats",
        f"- **CERTIFIED**: {certified} formats",
        "",
    ]

    # Product Limitations
    no_source_formats = [
        f.get("format_id", "?").upper()
        for f in formats_list
        if not f.get("has_source", False)
    ]

    lines += [
        _anchor("product-limitations"),
        "### Product Limitations",
        "",
    ]
    if no_source_formats:
        lines.append(
            f"- **Formats without source** ({len(no_source_formats)}): "
            f"{', '.join(no_source_formats)}"
        )
        # Mention ORA explicitly if in the list
        if "ORA" in no_source_formats:
            lines.append(
                "  - ORA and similar imaging formats have no Python source — "
                "oracle and certification not applicable"
            )
    lines.append("")

    return "\n".join(lines)


