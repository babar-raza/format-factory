"""Generate PROJECT_STATUS.md — canonical two-lane project status document.

Produces a structured document with stable HTML anchors separating Machinery Lane
(governance, validators, capabilities, skills, supervisor) from Product Lane
(formats, oracle, certification, gates, implementations).

Usage:
    python tools/docs/generate_project_status.py
    python tools/docs/generate_project_status.py --dry-run
    python tools/docs/generate_project_status.py --validate
    python tools/docs/generate_project_status.py --update-readme
    python tools/docs/generate_project_status.py --timestamp 2026-01-01T00:00:00+00:00
    python tools/docs/generate_project_status.py --output /tmp/status.md
"""

