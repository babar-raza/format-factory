class TestComposeVerifyDryRun:
    """ComposeVerifyLoop dry-run simulates full gate chain without writing files."""

    def test_safe_llm_output_passes_all_gates(self):
        loop = ComposeVerifyLoop()
        result = loop.run(
            feature_name="mock_llm_safe",
            template_content=MOCK_LLM_SAFE_OUTPUT,
            dry_run=True,
            queue_item_id="LLM-DRY-001",
            taskcard_id="LFI-6-F",
            target_format="ndjson",
        )
        assert result.ok is True
        assert result.dry_run is True
        assert result.g3_safe is True
        assert result.queue_item_id == "LLM-DRY-001"
        assert result.taskcard_id == "LFI-6-F"

    def test_forbidden_llm_output_blocked_by_g3(self):
        loop = ComposeVerifyLoop()
        result = loop.run(
            feature_name="mock_llm_forbidden",
            template_content=MOCK_LLM_FORBIDDEN_OUTPUT,
            dry_run=True,
        )
        assert result.ok is False
        assert result.g3_safe is False
        assert result.changed_files == []

    def test_aliased_forbidden_blocked_by_g3_v2(self):
        """v2 alias detection: sp.run() in mock LLM output is caught by gate."""
        loop = ComposeVerifyLoop()
        result = loop.run(
            feature_name="mock_llm_alias",
            template_content=MOCK_LLM_ALIASED_FORBIDDEN_OUTPUT,
            dry_run=True,
        )
        assert result.ok is False
        assert result.g3_safe is False

    def test_dry_run_result_is_json_serializable(self):
        loop = ComposeVerifyLoop()
        result = loop.run(
            feature_name="mock_dry_serial",
            template_content=MOCK_LLM_SAFE_OUTPUT,
            dry_run=True,
        )
        d = result.to_dict()
        json.dumps(d)  # must not raise
        assert d["dry_run"] is True
        assert d["g3_safe"] is True


