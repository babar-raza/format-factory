# ---------------------------------------------------------------------------
# Gate 1: py_compile (syntax check)
# ---------------------------------------------------------------------------


class TestG1SyntaxGate:
    """Gate 1: py_compile validates syntax of mock LLM output."""

    def test_safe_output_passes_syntax(self, tmp_path):
        p = tmp_path / "gen.py"
        p.write_text(MOCK_LLM_SAFE_OUTPUT, encoding="utf-8")
        try:
            py_compile.compile(str(p), doraise=True)
            passed = True
        except py_compile.PyCompileError:
            passed = False
        assert passed

    def test_forbidden_output_still_valid_syntax(self, tmp_path):
        """Forbidden calls are syntactically valid — G3 catches them, not G1."""
        p = tmp_path / "gen.py"
        p.write_text(MOCK_LLM_FORBIDDEN_OUTPUT, encoding="utf-8")
        try:
            py_compile.compile(str(p), doraise=True)
            passed = True
        except py_compile.PyCompileError:
            passed = False
        assert passed  # valid syntax — G3 is needed

    def test_syntax_error_fails_g1(self, tmp_path):
        p = tmp_path / "gen.py"
        p.write_text(MOCK_LLM_SYNTAX_ERROR, encoding="utf-8")
        with pytest.raises(py_compile.PyCompileError):
            py_compile.compile(str(p), doraise=True)


# ---------------------------------------------------------------------------
# Gate 3: AST forbidden-call scanner
# ---------------------------------------------------------------------------


class TestG3Gate:
    """Gate 3: G3 AST scanner catches forbidden calls in mock LLM output."""

    def test_safe_output_passes_g3(self):
        result = scan_source(MOCK_LLM_SAFE_OUTPUT, "mock_safe.py")
        assert result.safe is True
        assert len(result.findings) == 0

    def test_forbidden_output_caught_by_g3(self):
        result = scan_source(MOCK_LLM_FORBIDDEN_OUTPUT, "mock_forbidden.py")
        assert result.safe is False
        assert result.findings[0].symbol == "os.system"

    def test_aliased_forbidden_caught_by_g3_v2(self):
        """v2 alias hardening: sp.run() is now detected."""
        result = scan_source(MOCK_LLM_ALIASED_FORBIDDEN_OUTPUT, "mock_alias.py")
        assert result.safe is False
        assert result.findings[0].symbol == "subprocess.run"

    def test_from_import_forbidden_caught_by_g3_v2(self):
        """v2 from-import hardening: from subprocess import run; run() is detected."""
        result = scan_source(MOCK_LLM_FROM_IMPORT_FORBIDDEN, "mock_from_import.py")
        assert result.safe is False
        assert result.findings[0].symbol == "subprocess.run"

    def test_g3_scan_result_is_json_serializable(self):
        result = scan_source(MOCK_LLM_FORBIDDEN_OUTPUT, "mock.py")
        parsed = json.loads(result.to_json())
        assert parsed["safe"] is False
        assert len(parsed["findings"]) > 0


